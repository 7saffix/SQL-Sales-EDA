/*
Magnitude Analysis

Purpose:
    - To quantify data and group results by specific dimensions.
    - For understanding data distribution across categories.

SQL Functions Used:
    - Aggregate Functions: SUM(), COUNT(), AVG()
    - GROUP BY, ORDER BY

*/

-- Find total customers by countries
SELECT country ,count(*) FROM customers
GROUP BY country;

-- Find total customers by gender
SELECT gender,count(*) FROM customers
GROUP BY gender;

-- Find total products by category
SELECT category ,count(*) FROM products
GROUP BY category;

-- What is the average costs in each category?
SELECT category ,ROUND(AVG(cost),2) avg_cost FROM products
GROUP BY category
ORDER BY avg_cost DESC;

-- What is the total revenue generated for each category?
SELECT category, SUM(sales_amount)
 FROM Sales s 
JOIN products p 
ON s.product_key = p.product_key
GROUP BY category;


-- What is the total revenue generated by each customer?
SELECT c.customer_key,
c.first_name,
SUM(sales_amount) as total_revenue
FROM
sales s 
JOIN customers c 
ON s.customer_key = c.customer_key
GROUP BY c.customer_key,c.first_name
ORDER BY total_revenue DESC;


-- What is the distribution of sold items across countries?
SELECT c.country,
SUM(sales_amount) as total_revenue_country
FROM
sales s 
JOIN customers c 
ON s.customer_key = c.customer_key
GROUP BY c.country
ORDER BY total_revenue_country DESC;